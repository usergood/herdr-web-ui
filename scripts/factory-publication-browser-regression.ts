import "./test-herdr.ts";
import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { factoryPublicationFixture } from "../server/factory-publication.fixture.ts";

const f = await factoryPublicationFixture();
const browser = await chromium.launch({ executablePath: process.env["CHROME_PATH"] || chromium.executablePath(), headless: true, args: ["--no-sandbox"] });
try {
  await f.verify();
  assert.equal((await f.request(`/runs/${f.run.id}/accept`, { head: f.head })).status, 200);
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(10000);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`http://localhost:${f.app.port}/#factory/${f.run.implementation_id}`);
  const publication = page.getByRole("region", { name: "Implementation PR", exact: true });
  await publication.getByRole("button", { name: "Publish PR", exact: true }).waitFor();
  await publication.getByText("fictional/project · main", { exact: true }).waitFor();
  assert.equal(f.uploads.length, 0);
  assert(await publication.getByText(f.head, { exact: true }).count());
  await publication.getByRole("textbox", { name: "PR title", exact: true }).fill("fix(factory): preserve accepted delivery");
  await publication.getByRole("textbox", { name: "Problem and resulting behavior", exact: true }).fill("Delivery lost its accepted result. Preserve it with verification evidence.");
  f.github({ lose_receipt: true });
  const published = page.waitForResponse(r => r.url().endsWith(f.route + "/publish"));
  await publication.getByRole("button", { name: "Publish PR", exact: true }).focus();
  await page.keyboard.press("Enter");
  assert.equal((await published).status(), 200);
  await publication.getByText("Publication needs reconciliation", { exact: true }).waitFor();
  await page.reload();
  await publication.getByText("Publication needs reconciliation", { exact: true }).waitFor();
  assert.equal(await publication.getByRole("button", { name: "Publish PR", exact: true }).count(), 0);
  await page.setViewportSize({ width: 320, height: 844 });
  await publication.getByRole("button", { name: "Reconcile PR publication", exact: true }).click();
  await publication.getByRole("link", { name: "PR #42", exact: true }).waitFor();
  assert(await publication.evaluate(el => el.scrollWidth <= el.clientWidth + 1), "Publication fits a phone");
  assert.equal(f.calls().filter(c => c.args.includes("--method")).length, 1);
  await page.close();
  const settingsPage = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); settingsPage.setDefaultTimeout(10000);
  settingsPage.on("pageerror", error => errors.push(error.message));
  await settingsPage.goto(`http://localhost:${f.app.port}/#projects/${f.project.id}/settings`);
  await settingsPage.getByRole("tab", { name: "Workflow", exact: true }).click();
  const auto = settingsPage.getByRole("switch", { name: "Publish implementation PRs automatically", exact: true });
  await auto.waitFor(); assert.equal(await auto.getAttribute("aria-checked"), "false");
  await settingsPage.setViewportSize({ width: 320, height: 844 });
  assert(await settingsPage.getByRole("dialog", { name: "Project settings", exact: true }).evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  const configured = settingsPage.waitForResponse(r => r.url().endsWith(`/projects/${f.project.id}/configure`));
  await auto.click(); assert.equal((await configured).status(), 200);
  assert.equal((await f.request("").then(r => r.json())).projects.find((p: { id: string }) => p.id === f.project.id).auto_publish_pr, true);
  assert.deepEqual(errors, []);
  console.log("Implementation publication browser: explicit reviewed head, lost receipt/reload, phone recovery, separate default-off opt-in");
} finally { await browser.close(); await f.close(); }
