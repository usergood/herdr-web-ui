import "./test-herdr.ts";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "playwright-core";
import { factoryDeliveryFixture } from "../server/factory-delivery.fixture.ts";
import { paneRename } from "../server/herdr/client.ts";

const f = await factoryDeliveryFixture();
const browser = await chromium.launch({ executablePath: process.env["CHROME_PATH"] || chromium.executablePath(), headless: true, args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10_000);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const origin = `http://localhost:${f.app.port}`;
  await page.goto(`${origin}/#projects/${f.project.id}/settings`);
  const dialog = page.getByRole("dialog", { name: "Project settings", exact: true });
  await dialog.getByRole("tab", { name: "Workflow", exact: true }).click();
  const milestone = dialog.getByRole("combobox", { name: "Delivery milestone", exact: true });
  assert.equal(await milestone.count(), 1, "One Delivery milestone selector on desktop");
  assert.equal(await milestone.inputValue(), "merge");
  assert.equal(await dialog.getByRole("textbox", { name: "Delivery branch", exact: true }).inputValue(), "main");
  await milestone.selectOption("release");
  await dialog.getByRole("textbox", { name: "Delivery branch", exact: true }).fill("stable");
  const save = page.waitForResponse(r => r.url().endsWith(`/projects/${f.project.id}/configure`) && r.request().method() === "POST");
  await dialog.getByRole("button", { name: "Save Project settings", exact: true }).click();
  assert.equal((await save).status(), 200);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await milestone.count(), 1, "One Delivery milestone selector on mobile");
  assert.equal(await milestone.inputValue(), "release");
  assert(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), "Delivery settings fit a phone");
  await page.route("**/api/factory/project-discovery", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { code: "owned_discovery_failed", message: "Owned Project discovery failed" } }) }));
  await page.reload();
  await dialog.getByRole("tab", { name: "Workflow", exact: true }).click();
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await dialog.getByRole("alert").filter({ hasText: "Owned Project discovery failed" }).waitFor();
    assert.equal(await milestone.count(), 1);
    assert.equal(await dialog.getByRole("status").filter({ hasText: "Owned Project discovery failed" }).count(), 0);
  }
  await page.unroute("**/api/factory/project-discovery");
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  const run = await f.start();
  await paneRename(run.pane_id!, "Retained native research");
  const unfinished = await f.request("/implementations", { title: "Still unfinished", description: "Keep this discoverable", project_id: f.project.id }).then(r => r.json());
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${origin}/#factory/${run.implementation_id}`);
  const navigation = page.getByRole("navigation", { name: "Projects", exact: true });
  await navigation.getByText("Retained research", { exact: true }).waitFor();
  const accept = page.getByRole("button", { name: "Accept research", exact: true });
  assert.equal(await accept.isEnabled(), false, "Research requires a fresh evidence check");
  await page.getByRole("button", { name: "Check completion evidence", exact: true }).click();
  await accept.waitFor();
  const completion = page.waitForResponse(r => r.url().endsWith(`${f.prefix}/complete-work`) && r.request().method() === "POST");
  await accept.click();
  assert.equal((await completion).status(), 200);
  await page.getByRole("button", { name: "Archive task", exact: true }).waitFor();
  const completed = await f.request(f.prefix).then(r => r.json());
  assert.equal(completed.board.lane, "done");
  assert.equal(completed.implementation.outcome, "research_accepted");
  await navigation.getByText("Retained research", { exact: true }).waitFor({ state: "detached" });
  await page.getByRole("region", { name: "Agents", exact: true }).getByText("Retained native research", { exact: true }).waitFor({ state: "detached" });
  await navigation.getByText(unfinished.title, { exact: true }).waitFor();
  assert.equal((await f.request("").then(r => r.json())).implementations.some((idea: { id: string }) => idea.id === run.implementation_id), true, "Finished research stays available from the board");
  const stopped = await f.request("/implementations", { title: "Stopped research", description: "", project_id: f.project.id }).then(r => r.json());
  const stoppedPrefix = `/implementations/${stopped.id}`;
  const stoppedRun = await f.request(stoppedPrefix + "/runs", { action: "work", idempotency_key: "stopped-research" }).then(r => r.json());
  assert.equal((await f.request(`/runs/${stoppedRun.id}/stop`, {})).status, 200);
  await page.goto(`${origin}/#factory/${stopped.id}`);
  await page.getByRole("button", { name: "Check completion evidence", exact: true }).click();
  const stoppedCompletion = page.waitForResponse(r => r.url().endsWith(`${stoppedPrefix}/complete-work`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Accept research", exact: true }).click();
  assert.equal((await stoppedCompletion).status(), 200, "Research remains acceptable after an explicitly confirmed stop");
  const changing = await f.request("/implementations", { title: "Repository research", description: "", project_id: f.project.id }).then(r => r.json());
  const changingPrefix = `/implementations/${changing.id}`;
  const changingRun = await f.request(changingPrefix + "/runs", { action: "work", idempotency_key: "changing-research" }).then(r => r.json());
  await page.goto(`${origin}/#factory/${changing.id}`);
  const inspected = page.waitForResponse(r => r.url().endsWith(`${changingPrefix}/completion-evidence`));
  await page.getByRole("button", { name: "Check completion evidence", exact: true }).click();
  assert.equal((await (await inspected).json()).repository_changes, "none");
  await page.waitForFunction(() => [...document.querySelectorAll<HTMLButtonElement>("button")].some(button => button.textContent?.trim() === "Accept research" && !button.disabled));
  writeFileSync(join(changingRun.worktree, "findings.md"), "Repository documentation\n");
  f.git(["add", "findings.md"], changingRun.worktree);
  f.git(["-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "-m", "document findings"], changingRun.worktree);
  const rejected = page.waitForResponse(r => r.url().endsWith(`${changingPrefix}/complete-work`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Accept research", exact: true }).click();
  assert.equal((await rejected).status(), 409, "A previous browser check cannot accept new repository changes");
  const nextStep = page.getByRole("region", { name: "Next step", exact: true });
  await nextStep.getByText("Repository changes require verified PR delivery. Link the delivery evidence before completing this Assignment.", { exact: true }).waitFor();
  assert.equal(await nextStep.getByRole("button", { name: "Accept research", exact: true }).isEnabled(), false);
  assert.equal((await f.request(changingPrefix).then(r => r.json())).board.lane, "needs_you");
  assert(await nextStep.evaluate(el => el.scrollWidth <= el.clientWidth), "Completion blockers fit a phone");
  await navigation.getByText(changing.title, { exact: true }).waitFor();
  // Retained legacy outcomes are arranged through HTTP; current owner controls are Pause/Delete.
  assert.equal(await page.getByRole("button", { name: "Discard Assignment", exact: true }).count(), 0);
  assert.equal((await f.request(`${changingPrefix}/discard`, {})).status, 200);
  await page.reload();
  await page.getByRole("region", { name: "Next step", exact: true }).getByText("Discarded", { exact: true }).waitFor();
  await navigation.getByText(changing.title, { exact: true }).waitFor({ state: "detached" });
  await page.goto(`${origin}/#projects/${f.project.id}`);
  await page.getByRole("region", { name: "Done", exact: true }).getByRole("button", { name: changing.title, exact: true }).click();
  await page.getByRole("heading", { name: changing.title, exact: true }).waitFor();
  const retained = await f.request(changingPrefix).then(r => r.json());
  assert.equal(retained.implementation.outcome, "discarded");
  assert.equal(retained.runs[0].id, changingRun.id);
  assert.equal(retained.implementation.archived_at ?? null, null);
  await page.locator("summary").filter({ hasText: /^Advanced controls$/ }).first().click();
  await page.getByRole("heading", { name: "Past attempts", exact: true }).waitFor();
  const remote = await factoryDeliveryFixture(true);
  try {
    const remoteRun = await remote.start(); remote.disconnect();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`http://localhost:${remote.app.port}/#factory/${remoteRun.implementation_id}`);
    await page.getByRole("button", { name: "Check completion evidence", exact: true }).click();
    await page.getByRole("region", { name: "Next step", exact: true }).getByText("Repository change evidence is unavailable. Reconnect the Machine and inspect the retained work before accepting research.", { exact: true }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Accept research", exact: true }).count(), 0);
    assert.equal((await remote.request(remote.prefix).then(r => r.json())).board.lane, "needs_you");
    assert.equal(await page.getByRole("button", { name: "Discard Assignment", exact: true }).count(), 0);
    assert.equal((await remote.request(`${remote.prefix}/discard`, {})).status, 200);
    await page.reload();
    await page.getByRole("status", { name: "Discard pending", exact: true }).waitFor();
    assert.equal((await remote.request(remote.prefix).then(r => r.json())).board.sidebar_hidden, false);
    await page.reload();
    const pendingStep = page.getByRole("region", { name: "Next step", exact: true });
    const reconcileDiscard = pendingStep.getByRole("button", { name: "Reconcile Discard", exact: true });
    await reconcileDiscard.waitFor();
    assert(await pendingStep.evaluate(el => el.scrollWidth <= el.clientWidth), "Pending Discard fits a phone");
    assert((await reconcileDiscard.boundingBox())!.height >= 40, "Reconcile Discard has a usable phone touch target");
    assert.equal(await pendingStep.getByRole("button", { name: "Start work", exact: true }).count(), 0);
    remote.reconnect();
    const reconciled = page.waitForResponse(r => r.url().endsWith(`${remote.prefix}/discard`) && r.request().method() === "POST");
    await reconcileDiscard.click();
    assert.equal((await (await reconciled).json()).outcome, "discarded");
    await pendingStep.getByText("Discarded", { exact: true }).waitFor();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await navigation.getByText("Retained research", { exact: true }).waitFor({ state: "detached" });
  } finally { await remote.close(); }
  assert.deepEqual(errors, []);
  console.log("Delivery browser: frozen policy settings, accepted research, committed-change rejection and unknown Machine evidence on desktop/phone");
} finally { await browser.close(); await f.close(); }
