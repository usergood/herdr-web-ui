import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const icon = "data:image/png;base64," + readFileSync(join(root, "public/icons/icon-192.png")).toString("base64");
const badge = "data:image/png;base64," + readFileSync(join(root, "public/icons/badge-96.png")).toString("base64");
const generated = `/** Generated by bun scripts/generate-notification-icons.ts. Existing bundled PNG bytes, unchanged. */\nexport const NOTIFICATION_ICON = ${JSON.stringify(icon)};\nexport const NOTIFICATION_BADGE = ${JSON.stringify(badge)};\n`;
const begin = "// BEGIN BUNDLED_NOTIFICATION_ICONS";
const end = "// END BUNDLED_NOTIFICATION_ICONS";
const workerPath = join(root, "public/sw.js");
const worker = readFileSync(workerPath, "utf8");
const block = `${begin}\nconst NOTIFICATION_ICON = ${JSON.stringify(icon)};\nconst NOTIFICATION_BADGE = ${JSON.stringify(badge)};\n${end}`;
const updated = worker.includes(begin)
  ? worker.slice(0, worker.indexOf(begin)) + block + worker.slice(worker.indexOf(end) + end.length)
  : block + "\n\n" + worker;
const outputs = [[join(root, "shared/notification-icons.generated.ts"), generated], [workerPath, updated]] as const;
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content) throw new Error("Notification icons are stale; run bun scripts/generate-notification-icons.ts");
  } else writeFileSync(path, content);
}
